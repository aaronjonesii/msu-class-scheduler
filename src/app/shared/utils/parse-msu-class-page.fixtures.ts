interface ClassRow {
  optionNumber?: number,
  status?: string,
  components?: string[],
  times?: string[],
  rooms?: string[],
  instructors?: string[],
  seats?: string[],
}

/** A table row in the same one-cell-per-line shape as the real pages. */
export function classRow(row: ClassRow = {}): string {
  const {
    optionNumber = 1,
    status = 'Open',
    components = ['Class Comp Lecture - Class Sect 001 -'],
    times = ['Monday', '9:10AM to 10:00AM'],
    rooms = ['Wells Hall A1'],
    instructors = ['Ann Lee'],
    seats = ['Open Seats 1 of 9'],
  } = row;

  return [
    optionNumber, status, 'Regular Academic Session', ...components,
    '01/19/2027 - 05/02/2027', ...times, ...rooms, ...instructors, ...seats,
  ].join('\n');
}

